#!/usr/bin/env node
// Lists the licence of every installed package (node_modules, all depths) and fails on GPL or AGPL.
// LGPL is accepted only for the packages in scripts/lgpl-allowlist.json (separate, replaceable
// modules under app/workers/ with their notices). With --write it also writes THIRD_PARTY_LICENSES.md
// (generated at build time, not committed). Run: npm run check:licenses
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const write = process.argv.includes('--write');
const allow = JSON.parse(readFileSync(join(root, 'scripts/lgpl-allowlist.json'), 'utf8'));

/** Every package.json under a node_modules folder, recursively (scoped packages included). */
function* packages(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    if (name.startsWith('.')) continue;
    const p = join(dir, name);
    if (name.startsWith('@')) {
      for (const sub of readdirSync(p)) yield* packageAt(join(p, sub));
    } else yield* packageAt(p);
  }
}
function* packageAt(p) {
  const pj = join(p, 'package.json');
  if (!existsSync(pj) || !statSync(p).isDirectory()) return;
  yield p;
  yield* packages(join(p, 'node_modules'));
}

/** The licence as a string: the `license` field, else the first line of a LICENSE file, else '?'. */
function licenseOf(dir, pkg) {
  const l = pkg.license ?? pkg.licence;
  if (typeof l === 'string' && l) return l;
  if (l && typeof l === 'object' && typeof l.type === 'string') return l.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((x) => (typeof x === 'string' ? x : x.type)).join(' OR ');
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f));
  if (file) {
    const head = readFileSync(join(dir, file), 'utf8').slice(0, 400);
    if (/MIT License/i.test(head)) return 'MIT (from LICENSE file)';
    if (/Apache License/i.test(head)) return 'Apache-2.0 (from LICENSE file)';
    if (/BSD/i.test(head)) return 'BSD (from LICENSE file)';
    if (/ISC/i.test(head)) return 'ISC (from LICENSE file)';
    return `see ${file}`;
  }
  return '?';
}

const seen = new Map();
for (const dir of packages(join(root, 'node_modules'))) {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  if (!pkg.name) continue;
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) continue;
  seen.set(key, { name: pkg.name, version: pkg.version, license: licenseOf(dir, pkg), url: pkg.homepage ?? pkg.repository?.url ?? '' });
}

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const isForbidden = (l) => /\b(A?GPL)\b/i.test(l) && !/\bLGPL\b/i.test(l);
// A dual licence like "(MIT OR GPL-2.0)" is fine: we take the MIT side.
const dual = (l) => /\bOR\b/i.test(l);
const bad = rows.filter((r) => isForbidden(r.license) && !dual(r.license));
const lgpl = rows.filter((r) => /\bLGPL\b/i.test(r.license) && !dual(r.license) && !allow.includes(r.name));
const unknown = rows.filter((r) => r.license === '?');

if (write) {
  const lines = [
    '# Third-party licences',
    '',
    `Generated by scripts/check-licenses.mjs from the installed packages (${rows.length}). MechPilot itself is Apache-2.0 (see LICENSE and NOTICE).`,
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
    ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
    '',
  ];
  writeFileSync(join(root, 'THIRD_PARTY_LICENSES.md'), lines.join('\n'));
}

console.log(`${rows.length} packages checked`);
for (const r of unknown) console.log(`  no licence found for ${r.name}@${r.version} (check by hand)`);
if (bad.length) {
  console.error('GPL/AGPL packages are not allowed (CLAUDE.md, Licences):');
  for (const r of bad) console.error(`  ${r.name}@${r.version}: ${r.license}`);
}
if (lgpl.length) {
  console.error('LGPL packages must be listed in scripts/lgpl-allowlist.json with a notice under app/workers/:');
  for (const r of lgpl) console.error(`  ${r.name}@${r.version}: ${r.license}`);
}
process.exit(bad.length || lgpl.length ? 1 : 0);
